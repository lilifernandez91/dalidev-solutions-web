export const getPalmaresData = (season) => {
    const items = palmaresData;
    if (season) {
        items = items.filter((item) => item.season === season);
    }

    const itemsWIthLeagueName = items.map((item) => {
        const competition = competitions.find((competition) => competition.id === item.league);
        return {
            ...item,
            name: competition.name,
            double: competition.double,
        };
    });

    return itemsWIthLeagueName;
};
